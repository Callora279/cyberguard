import useSWR from "swr";
import {
  BarChart, Bar, LineChart, Line, XAxis, YAxis, Tooltip, ResponsiveContainer, CartesianGrid,
} from "recharts";
import { fetcher } from "../lib/api";

const HORIZONS = ["30d", "60d", "90d"];

export default function PredictiveRisk() {
  const { data } = useSWR("/risk-score/forecast?horizon_days=30", fetcher, { refreshInterval: 60000 });
  const { data: trendData } = useSWR("/risk-score/trend", fetcher, { refreshInterval: 60000 });
  const incident = data?.incident_forecast;
  const multi = data?.multi_horizon;
  const aiForecast = data?.ai_forecast;

  const chartData = (incident?.predictions || []).map((p) => ({
    vector: p.vector.replace(/_/g, " "),
    probability: Math.round(p.probability * 100),
  }));

  const trendChartData = (trendData?.trend?.points || []).map((p) => ({
    date: new Date(p.t).toLocaleString([], { month: "short", day: "numeric", hour: "2-digit", minute: "2-digit" }),
    score: Math.round(p.score),
  }));

  return (
    <div className="grid" style={{ gap: 20 }}>
      <h2>Predictive Risk</h2>

      <div className="card">
        <h3>Headline</h3>
        <div className="big" style={{ fontSize: 22 }}>{incident?.headline || "…"}</div>
      </div>

      {trendData?.score_drop?.dropped && (
        <div className="card" style={{ borderColor: "var(--crit)" }}>
          <h3 style={{ color: "var(--crit)" }}>⚠ Risk score dropped {trendData.score_drop.drop} points</h3>
          <p className="muted">
            {trendData.score_drop.previous?.toFixed(1)} → {trendData.score_drop.current?.toFixed(1)}
            {" "}(alert threshold: {trendData.score_drop.threshold} points)
          </p>
        </div>
      )}

      <div className="card">
        <h3>Risk Score Trend</h3>
        <p className="muted">
          Direction: <strong style={{ textTransform: "capitalize" }}>{trendData?.trend?.direction || "…"}</strong>
          {" "}· confidence {trendData?.trend?.confidence || "…"}
          {trendData?.trend?.trending_bad_modules?.length > 0 && (
            <> · trending bad: {trendData.trend.trending_bad_modules.join(", ")}</>
          )}
        </p>
        <div style={{ width: "100%", height: 220 }}>
          <ResponsiveContainer>
            <LineChart data={trendChartData}>
              <CartesianGrid stroke="#232b3a" />
              <XAxis dataKey="date" stroke="#8b94a7" />
              <YAxis domain={[0, 100]} stroke="#8b94a7" />
              <Tooltip contentStyle={{ background: "#141924", border: "1px solid #232b3a" }} />
              <Line type="monotone" dataKey="score" stroke="#22c55e" strokeWidth={2} dot={false} />
            </LineChart>
          </ResponsiveContainer>
        </div>
      </div>

      <div className="card">
        <h3>Attack Probability (next 30 days)</h3>
        <div style={{ width: "100%", height: 260 }}>
          <ResponsiveContainer>
            <BarChart data={chartData} layout="vertical" margin={{ left: 60 }}>
              <CartesianGrid stroke="#232b3a" />
              <XAxis type="number" domain={[0, 100]} stroke="#8b94a7" />
              <YAxis type="category" dataKey="vector" width={140} stroke="#8b94a7" />
              <Tooltip contentStyle={{ background: "#141924", border: "1px solid #232b3a" }} />
              <Bar dataKey="probability" fill="#f97316" />
            </BarChart>
          </ResponsiveContainer>
        </div>
      </div>

      <div className="card">
        <h3>30 / 60 / 90 Day AI Risk Forecast</h3>
        {aiForecast?.horizons?.["30d"]?.source === "ai" && (
          <p className="muted" style={{ fontSize: 12 }}>
            The 30-day forecast below was generated by your configured AI model.
            {" "}Powered by {aiForecast.horizons["30d"].provider || "groq"} · {aiForecast.horizons["30d"].model}
          </p>
        )}
        <div className="grid" style={{ gridTemplateColumns: "1fr 1fr 1fr", gap: 16 }}>
          {HORIZONS.map((h) => (
            <div key={h}>
              <h4 style={{ marginBottom: 8 }}>{h} outlook</h4>
              {(aiForecast?.horizons?.[h]?.risks || []).map((r, i) => (
                <div key={i} style={{ marginBottom: 14 }}>
                  <div className="row" style={{ justifyContent: "space-between" }}>
                    <strong style={{ fontSize: 13 }}>{r.name}</strong>
                    <span className="muted" style={{ fontSize: 12 }}>{r.probability}%</span>
                  </div>
                  <div style={{ background: "#1c2330", borderRadius: 6, height: 6, marginTop: 4 }}>
                    <div style={{
                      width: `${r.probability}%`, height: 6, borderRadius: 6,
                      background: r.probability >= 60 ? "var(--crit)" : r.probability >= 30 ? "#f97316" : "var(--low)",
                    }} />
                  </div>
                  {r.impact && <p className="muted" style={{ fontSize: 11, marginTop: 4 }}>Impact: {r.impact}</p>}
                  {r.recommended_action && <p style={{ fontSize: 11, marginTop: 2 }}>→ {r.recommended_action}</p>}
                </div>
              ))}
              {!(aiForecast?.horizons?.[h]?.risks || []).length && <p className="muted">{multi?.horizons?.[h]?.headline || "…"}</p>}
            </div>
          ))}
        </div>
      </div>

      <div className="card">
        <h3>Threat Intelligence Feed</h3>
        <ul>
          {(data?.multi_horizon?.threat_landscape?.emerging_vectors || []).map((v) => <li key={v}>{v}</li>)}
        </ul>
        <h3 style={{ marginTop: 16 }}>Proactive Recommendations</h3>
        <ul>
          {(multi?.proactive_recommendations || []).map((r) => <li key={r}>{r}</li>)}
        </ul>
      </div>
    </div>
  );
}
